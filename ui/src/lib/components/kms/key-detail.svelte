<script lang="ts">
  import { ArrowRightIcon, CheckIcon, CopyIcon } from "phosphor-svelte";
  import RcPanel from "#lib/components/rack/rc-panel.svelte";
  import RcKv from "#lib/components/rack/rc-kv.svelte";
  import RcStat from "#lib/components/rack/rc-stat.svelte";
  import RcButton from "#lib/components/rack/rc-button.svelte";
  import RcTonePill from "#lib/components/rack/rc-tone-pill.svelte";
  import { formatJSONForViewer } from "#lib/json-format";
  import {
    kmsKeyName,
    kmsManagerLabel,
    kmsOperationCount,
    kmsReferenceLabel,
    kmsReferenceTarget,
    kmsStateLabel,
    kmsStateTone,
  } from "#lib/kms";
  import type { KmsKeySummary } from "#lib/types";
  import { formatDate, timeAgo } from "#lib/utils";

  let { key, onNavigate }: { key: KmsKeySummary; onNavigate: (target: string) => void } = $props();

  const name = $derived(kmsKeyName(key));
  const operations = $derived(kmsOperationCount(key));
  const tags = $derived(Object.entries(key.tags ?? {}).sort(([a], [b]) => a.localeCompare(b)));
  const policy = $derived(key.policy ? formatJSONForViewer(key.policy) : null);
  const usedByKinds = $derived([...new Set(key.usedBy.map(kmsReferenceLabel))]);

  // Bars are scaled to the busiest operation so small counts stay visible.
  const activity = $derived.by(() => {
    const rows = [
      { label: "Decrypt", count: key.usage.decrypt },
      { label: "Encrypt", count: key.usage.encrypt },
      { label: "Data keys", count: key.usage.dataKeys },
      { label: "Re-encrypt", count: key.usage.reEncrypt },
    ];
    const max = Math.max(1, ...rows.map((r) => r.count));
    return rows.map((r) => ({ ...r, share: r.count / max }));
  });

  const details = $derived([
    { label: "Key ID", value: key.id, mono: true },
    { label: "ARN", value: key.arn, mono: true, dim: true },
    { label: "Description", value: key.description || "--" },
    { label: "Key spec", value: "SYMMETRIC_DEFAULT", mono: true },
    { label: "Key usage", value: "ENCRYPT_DECRYPT", mono: true },
    { label: "Origin", value: "AWS_KMS · material generated by Tarn", mono: true, dim: true },
    { label: "Rotation", value: key.rotationEnabled ? `Every ${key.rotationPeriodDays ?? 365} days · recorded only` : "Off" },
    { label: "Created", value: formatDate(key.created) },
    ...(key.deletionDate ? [{ label: "Deletes", value: formatDate(key.deletionDate) }] : []),
  ]);

  let copied = $state<string | null>(null);
  let copyTimer: ReturnType<typeof setTimeout> | undefined;
  async function copy(text: string, field: string) {
    try {
      await navigator.clipboard.writeText(text);
      copied = field;
      clearTimeout(copyTimer);
      copyTimer = setTimeout(() => (copied = null), 1600);
    } catch {}
  }
</script>

<div class="detail">
  <header class="hero">
    <div class="identity">
      <div class="title-row">
        <h1 title={name}>{name}</h1>
        <RcTonePill tone={kmsStateTone(key.state)}>{kmsStateLabel(key.state)}</RcTonePill>
      </div>
      <div class="subline">
        <span>{kmsManagerLabel(key.manager)}</span><i></i>
        <button type="button" class="arn" title="Copy ARN" onclick={() => copy(key.arn, "arn")}>
          <span>{key.arn}</span>
          {#if copied === "arn"}<CheckIcon size={11} />{:else}<CopyIcon size={11} />{/if}
        </button>
      </div>
    </div>
  </header>

  {#if key.deletionDate}
    <p class="banner">
      Scheduled for deletion {formatDate(key.deletionDate)}. Encrypt and decrypt fail until the deletion is cancelled.
    </p>
  {:else if key.state === "Disabled"}
    <p class="banner amber">Disabled. Encrypt and decrypt fail until the key is enabled.</p>
  {/if}

  <div class="stats">
    <RcStat label="Operations" value={operations} sub="since Tarn started" />
    <RcStat
      label="Last used"
      value={key.usage.lastUsed ? timeAgo(key.usage.lastUsed) : "--"}
      sub={key.usage.lastUsed ? formatDate(key.usage.lastUsed) : "not used yet"}
    />
    <RcStat
      label="Failures"
      value={key.usage.failures}
      tone={key.usage.failures > 0 ? "red" : undefined}
      sub={key.usage.lastError ?? "none"}
    />
    <RcStat label="Used by" value={key.usedBy.length} sub={usedByKinds.join(", ") || "no resources"} />
  </div>

  <RcPanel title="Used by" description="Resources whose configuration names this key" index={0}>
    {#if key.usedBy.length}
      <div class="refs">
        {#each key.usedBy as ref (`${ref.kind}:${ref.id ?? ref.name}`)}
          <button type="button" class="ref" onclick={() => onNavigate(kmsReferenceTarget(ref))}>
            <span class="ref-kind">{kmsReferenceLabel(ref)}</span>
            <span class="ref-name" title={ref.name}>{ref.name}</span>
            <span class="ref-field">{ref.field}</span>
            <ArrowRightIcon size={12} />
          </button>
        {/each}
      </div>
    {:else}
      <p class="note">No resource names this key. Code can still call it directly, for example a Lambda function decrypting a Cognito code.</p>
    {/if}
  </RcPanel>

  <RcPanel title="Activity" description="Successful operations since Tarn started" index={1}>
    <div class="activity">
      {#each activity as row (row.label)}
        <div class="op">
          <span class="op-label">{row.label}</span>
          <span class="track"><span class="fill" style:transform="scaleX({row.share})"></span></span>
          <span class="op-count">{row.count}</span>
        </div>
      {/each}
    </div>
    {#if key.usage.lastError}
      <p class="last-error">
        Last failure <b>{key.usage.lastError}</b>
        {#if key.usage.lastErrorAt}<span>{timeAgo(key.usage.lastErrorAt)}</span>{/if}
      </p>
    {/if}
  </RcPanel>

  <RcPanel title="Details" index={2}>
    <RcKv items={details} labelWidth="7rem" />
  </RcPanel>

  <RcPanel title="Aliases" description="{key.aliases.length} alias{key.aliases.length === 1 ? '' : 'es'}" index={3}>
    {#if key.aliases.length}
      <div class="chips">
        {#each key.aliases as alias (alias)}
          <button type="button" class="chip" title="Copy alias" onclick={() => copy(alias, alias)}>
            {alias}
            {#if copied === alias}<CheckIcon size={10} />{:else}<CopyIcon size={10} />{/if}
          </button>
        {/each}
      </div>
    {:else}
      <p class="note">No aliases. Refer to this key by its ID or ARN.</p>
    {/if}
  </RcPanel>

  <RcPanel title="Key policy" description="Stored, not enforced" index={4}>
    {#snippet actions()}
      {#if key.policy}
        <RcButton small variant="ghost" onclick={() => copy(key.policy, "policy")}>
          {#if copied === "policy"}<CheckIcon size={11} />Copied{:else}<CopyIcon size={11} />Copy{/if}
        </RcButton>
      {/if}
    {/snippet}
    {#if policy}
      <pre>{@html policy.formattedHtml}</pre>
    {:else if key.policy}
      <pre>{key.policy}</pre>
    {:else}
      <p class="note">No policy.</p>
    {/if}
  </RcPanel>

  <RcPanel title="Tags" description="{key.tagCount} tag{key.tagCount === 1 ? '' : 's'}" index={5}>
    {#if tags.length}
      <div class="chips">
        {#each tags as [k, v] (k)}
          <span class="tag"><b>{k}</b>{v}</span>
        {/each}
      </div>
    {:else}
      <p class="note">No tags on this key.</p>
    {/if}
  </RcPanel>
</div>

